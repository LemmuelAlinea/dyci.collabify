/**
 * Two interlocking forms — a collaboration mark. The amber stays amber in every
 * theme; the dark half is painted through currentColor because the mark carries
 * no plate, so navy on a dark surface would all but disappear.
 */
export function LogoMark({ size = 32, tone = 'brand' }: Props) {
  const ink =
    tone === 'onDark'
      ? 'text-white'
      : tone === 'brand'
        ? 'text-[#2A3585] dark:text-white'
        : ''

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 1024 1024"
      fill="none"
      aria-hidden="true"
      className={`shrink-0 ${ink}`}
    >
      <path fill="#F5A623" d={ACCENT} />
      <path fill="currentColor" d={INK} />
    </svg>
  )
}

export function Logo({
  size = 34,
  tone = 'brand',
  subtitle = 'Project workspace',
  showSubtitle = true,
}: Props & { subtitle?: string; showSubtitle?: boolean }) {
  // The wordmark used to inherit body colour, so on the navy sidebar it turned
  // near-black in light mode. Each tone now states its own colour.
  const word =
    tone === 'onDark' ? 'text-white' : tone === 'brand' ? 'text-navy-600 dark:text-white' : ''
  const sub = tone === 'onDark' ? 'text-white/60' : 'text-muted'

  return (
    <span className="flex items-center gap-3">
      <LogoMark size={size} tone={tone} />
      <span className="flex flex-col leading-none">
        <span className={`font-display text-[19px] font-extrabold tracking-[-0.04em] ${word}`}>
          Collabify
        </span>
        {showSubtitle && <span className={`eyebrow mt-1 text-[12px] ${sub}`}>{subtitle}</span>}
      </span>
    </span>
  )
}
