// Writes js/timings.js and index.html from timings.json and tools/index.template.html.
// Scene windows open 0.5 s before a beat and close 0.5 s after the next one, so cuts can overlap.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const T = JSON.parse(readFileSync(join(root, 'timings.json'), 'utf8'));
const ids = Object.keys(T).filter((k) => k !== 'end');
const r2 = (n) => Math.round(n * 100) / 100;

writeFileSync(join(root, 'js/timings.js'), `/* generated by tools/build-index.mjs from timings.json */\nwindow.T = ${JSON.stringify(T)};\n`);

const sections = ids.map((id, i) => {
  const start = Math.max(0, T[id] - 0.5);
  const end = Math.min(T.end, (i + 1 < ids.length ? T[ids[i + 1]] : T.end) + 0.5);
  return `  <section id="${id}" class="scene clip" data-start="${r2(start)}" data-duration="${r2(end - start)}" data-track-index="${i + 1}"></section>`;
}).join('\n');
const scripts = ids.map((id) => `<script src="js/${id}.js"></script>`).join('\n');

const html = readFileSync(join(root, 'tools/index.template.html'), 'utf8')
  .replaceAll('{{END}}', String(T.end))
  .replace('{{SECTIONS}}', sections)
  .replace('{{SCRIPTS}}', scripts);
writeFileSync(join(root, 'index.html'), html);
console.log(`index.html: ${ids.length} scenes, ${T.end} s`);
